-- Уже созданные форумы: стоимость из мастер-плана по совпадению описания задачи
UPDATE "Task" AS t
SET "cost" = tt."cost"
FROM "TemplateTask" AS tt
WHERE lower(btrim(t."description")) = lower(btrim(tt."description"))
  AND tt."cost" > 0
  AND t."cost" = 0;
