-- СнабТех Китай: стоимость задач по смете «СнабТех'26. Строительство будущего. Китай» (лист «СнабТех», столбец «План»).
-- Каждая статья сметы отнесена к одной задаче, направление — по разделу сметы.
-- Остальные задачи форума обнуляются: в «Расходах» только суммы из сметы (итого 18 477 730 ₽).
-- Задача ищется по описанию из мастер-плана, если не найдена — по номеру.
DO $$
DECLARE
  fid INTEGER;
  r RECORD;
  tid INTEGER;
BEGIN
  SELECT "id" INTO fid
  FROM "Forum"
  WHERE "name" ~ '[Сс][Нн][Аа][Бб][ -]?[Тт][Ее][Хх]'
  ORDER BY
    "archived",
    (coalesce("name", '') || ' ' || coalesce("location", '')) ~ '[Кк][Ии][Тт][Аа][Йй]' DESC,
    "startDate" DESC
  LIMIT 1;

  IF fid IS NULL THEN
    RAISE NOTICE 'Форум СнабТех не найден — стоимость задач не изменена';
    RETURN;
  END IF;

  UPDATE "Task" SET "cost" = 0 WHERE "forumId" = fid;

  FOR r IN
    SELECT * FROM (VALUES
      -- Организационные: площадка и экскурсии (Future TMC), деловая программа (Рободжобс)
      (16, 'Выбрать площадку и подрядчика, согласовать условия сотрудничества', 1057425, 'org'), -- аренда зала 629 709,29 + сопровождение Future 285 000 + вознаграждение агентства 142 715,78
      (92, 'Получить смету и конфигурацию технических услуг от подрядчика', 231325, 'org'), -- комплект AV-оборудования
      (84, 'Забронировать и арендовать транспорт (трансфер, шаттл на территории площадки)', 139650, 'org'), -- аренда автобуса
      (85, 'Разработать сценарий экскурсионной программы', 787170, 'org'), -- снэки, гиды, билеты в сад, аудиогид, чайная церемония
      (89, 'Согласовать меню', 513000, 'org'), -- обед Shu Yan Fu
      (23, 'Выбрать подрядчика по работе со спикерами и программой (если привлекается внешний партнер)', 7011974, 'org'), -- расходы Рободжобс
      -- Типография
      (97, 'Изготовить мерч, сувениры и подарки для всех категорий участников и гостей', 61466, 'print'), -- бейджи, наклейки, дизайн, сумки
      -- Маркетинг
      (40, 'Разработать поканальный план продвижения форума и медиабюджет', 1533554, 'marketing'), -- Яндекс, посевы в ТГ, СМС, резерв, экраны СнабТех
      (41, 'Выбрать и законтрактовать подрядчика по маркетинговому продвижению', 368880, 'marketing'), -- интеграции PR-менеджера
      (67, 'Запустить и вести коммуникационную кампанию «подогрева» аудитории между регистрацией и форумом (email-цепочки, контент-план, анонсы)', 455252, 'marketing'), -- SMM, промо-мероприятия, чайная церемония
      (39, 'Подготовить прототип сайта форума', 50379, 'marketing'), -- веб-дизайнер
      (95, 'Составить список носителей / контента для передачи в работу дизайнеру', 121716, 'marketing'), -- дизайн Честухина
      (98, 'Напечатать финальную версию программы и иных раздаточных материалов', 32785, 'marketing'), -- печать полиграфии
      (38, 'Подготовить базу для аутрич и обзвона', 34440, 'marketing'), -- база Китай
      -- Наемный персонал
      (27, 'Сформировать отдел продаж: подбор и найм персонала', 2658198, 'staff'), -- отдел продаж
      (33, 'Разработана система мотивации - оклад, премии, проценты, KPI', 771946, 'staff'), -- премия ОП
      (42, 'Сформировать организационную структуру проектной команды и зоны ответственности по направлениям', 1414313, 'staff'), -- ивент-менеджер + Телегина
      (99, 'Выбрать и согласовать фотографа, актуализировать стоимость услуг', 250000, 'staff'), -- фото и видео
      (30, 'Настройка CRM: воронка, этапы, поля сделок, причины закрытия, роботы, подключены интеграции - почта, мессенджеры, телефония, создание документов', 30057, 'staff'), -- почта, аккаунты
      -- Командировочные
      (15, 'Провести инспекционный визит на выбранную(ые) площадку(и)', 628264, 'travel'), -- перелёт, проживание, приезды РОП
      -- Прочие
      (6, 'Разработать предварительную смету (бюджет) мероприятия', 325936, 'other') -- прочие расходы 2% от сметы
    ) AS v(num, descr, cost, cat)
  LOOP
    SELECT "id" INTO tid
    FROM "Task"
    WHERE "forumId" = fid
      AND regexp_replace(btrim("description"), '\s+', ' ', 'g') = r.descr
    ORDER BY "number"
    LIMIT 1;

    IF tid IS NULL THEN
      SELECT "id" INTO tid FROM "Task" WHERE "forumId" = fid AND "number" = r.num ORDER BY "id" LIMIT 1;
    END IF;

    IF tid IS NULL THEN
      RAISE NOTICE 'СнабТех: не найдена задача № % (% ₽)', r.num, r.cost;
    ELSE
      UPDATE "Task" SET "cost" = r.cost, "expenseCategory" = r.cat WHERE "id" = tid;
    END IF;
  END LOOP;
END $$;
